// Writes docs/dependencies.md: the third-party packages shipped in the
// extension (runtime) and the tooling used to build and test it (dev).
// Fails if a runtime dependency has a license outside the allowlist.
// Reads node_modules directly (run `npm ci` first); spawns no processes.
// Usage: node scripts/license-inventory.mjs [--check]
//   --check  fail if docs/dependencies.md is out of date instead of writing it
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Permissive licenses compatible with distributing the extension under MIT.
// Unlicense (public-domain dedication, OSI-approved) is used by fast-sha256,
// a dependency of the official Anthropic SDK.
const RUNTIME_ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "Unlicense"]);
const OUT = "docs/dependencies.md";
const WORKSPACE_SCOPE = "@mail2code/";

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === "string") return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(" OR ");
  if (l && typeof l === "object") return l.type ?? "UNKNOWN";
  return "UNKNOWN";
}

// Every installed third-party package, including nested node_modules.
function installed(dir, into = new Map()) {
  if (!existsSync(dir)) return into;
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".")) continue;
    const names = entry.startsWith("@") ? readdirSync(join(dir, entry)).map((n) => `${entry}/${n}`) : [entry];
    for (const name of names) {
      const pkgDir = join(dir, name);
      const manifest = join(pkgDir, "package.json");
      if (!existsSync(manifest) || name.startsWith(WORKSPACE_SCOPE)) continue;
      const pkg = readJson(manifest);
      into.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), dir: pkgDir });
      installed(join(pkgDir, "node_modules"), into);
    }
  }
  return into;
}

// Resolves a dependency the way Node does: nearest node_modules upward.
function resolveDir(name, fromDir) {
  for (let d = fromDir; ; d = join(d, "..")) {
    const candidate = join(d, "node_modules", name, "package.json");
    if (existsSync(candidate)) return join(d, "node_modules", name);
    if (join(d, "..") === d || d === ".") break;
  }
  return existsSync(join("node_modules", name, "package.json")) ? join("node_modules", name) : null;
}

// Production closure of the extension: its dependencies, followed through
// workspace packages and third-party packages (dependencies only, not dev).
function runtimeClosure() {
  const seen = new Map();
  const stack = [{ dir: "apps/extension" }];
  const visitedDirs = new Set();
  while (stack.length) {
    const { dir } = stack.pop();
    if (visitedDirs.has(dir)) continue;
    visitedDirs.add(dir);
    const pkg = readJson(join(dir, "package.json"));
    for (const name of Object.keys(pkg.dependencies ?? {})) {
      const depDir = name.startsWith(WORKSPACE_SCOPE) ? join("packages", name.slice(WORKSPACE_SCOPE.length)) : resolveDir(name, dir);
      if (!depDir) throw new Error(`Cannot resolve ${name} from ${dir}. Run npm ci first.`);
      if (!name.startsWith(WORKSPACE_SCOPE)) {
        const dep = readJson(join(depDir, "package.json"));
        seen.set(`${dep.name}@${dep.version}`, { name: dep.name, version: dep.version, license: licenseOf(dep) });
      }
      stack.push({ dir: depDir });
    }
  }
  return seen;
}

const runtime = runtimeClosure();
const dev = [...installed("node_modules").values()].filter((d) => !runtime.has(`${d.name}@${d.version}`));
const runtimeRows = [...runtime.values()].sort((a, b) => a.name.localeCompare(b.name));
const bad = runtimeRows.filter((r) => !RUNTIME_ALLOWED.has(r.license));

const devCounts = new Map();
for (const d of dev) devCounts.set(d.license, (devCounts.get(d.license) ?? 0) + 1);
const devLicenseRows = [...devCounts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

const md = [
  "# Dependencies and licenses",
  "",
  "Generated by `node scripts/license-inventory.mjs`. Do not edit by hand.",
  "",
  "## Shipped in the extension (runtime)",
  "",
  `These are bundled into the built extension. Allowed licenses: ${[...RUNTIME_ALLOWED].join(", ")}.`,
  "",
  "| Package | Version | License |",
  "|---|---|---|",
  ...runtimeRows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
  "## Build and test tooling (not shipped)",
  "",
  `${dev.length} installed packages are used only on developer machines and in CI (WXT, Vite, TypeScript, Vitest, Playwright and their dependencies). The count can differ slightly between operating systems because of platform-specific optional packages. By license:`,
  "",
  "| License | Packages |",
  "|---|---|",
  ...devLicenseRows.map(([l, n]) => `| ${l} | ${n} |`),
  "",
  "Run `npm ls --all` for the full list.",
  "",
].join("\n");

if (bad.length) {
  console.error(`✗ Runtime dependencies with disallowed licenses:\n${bad.map((b) => `  ${b.name}@${b.version}: ${b.license}`).join("\n")}`);
  process.exit(1);
}
if (process.argv.includes("--check")) {
  // Only the runtime section must match exactly; dev counts vary by platform.
  const section = (s) => s.split("## Build and test tooling")[0];
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (section(current) !== section(md)) {
    console.error(`✗ The runtime section of ${OUT} is out of date. Run: node scripts/license-inventory.mjs`);
    process.exit(1);
  }
  console.log(`✓ ${OUT} runtime section is up to date (${runtimeRows.length} runtime package(s), all with allowed licenses)`);
} else {
  writeFileSync(OUT, md);
  console.log(`✓ Wrote ${OUT}: ${runtimeRows.length} runtime package(s), ${dev.length} dev packages`);
}
